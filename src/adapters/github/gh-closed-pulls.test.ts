import { expect, test } from "bun:test";
import { FakeProcessRunner } from "../../testing/fake-process-runner";
import { GhClosedPulls, MAX_CLOSED_PULLS } from "./gh-closed-pulls";

const SINCE = Date.UTC(2026, 9, 27, 12);

const ghPull = (number: number, closedAt = "2026-11-02T00:00:00Z") => ({
  number,
  title: "fix: thing",
  body: "Generated by `shipwright pipeline`",
  headRefName: "ci/issue-1",
  labels: [{ name: "shipwright:test-run" }],
  createdAt: "2026-11-01T00:00:00Z",
  mergedAt: null,
  closedAt,
});

function runner(prefix: string[], stdout: string, exitCode = 0, stderr = "") {
  return new FakeProcessRunner([{ prefix, result: { exitCode, stdout, stderr } }]);
}
const list = (stdout: string, exitCode = 0, stderr = "") =>
  runner(["gh", "pr", "list"], stdout, exitCode, stderr);

test("keeps the merge commit when GitHub returns one", async () => {
  const merged = {
    ...ghPull(8),
    mergedAt: "2026-11-02T00:00:00Z",
    mergeCommit: { oid: "abc1234def" },
  };
  const r = await new GhClosedPulls(list(JSON.stringify([merged]))).closedSince(SINCE);
  expect(r.ok && r.value.pulls[0]?.mergeSha).toBe("abc1234def");
});

test("lists every closed PR without search and keeps those closed in the window", async () => {
  const old = ghPull(6, "2026-10-01T00:00:00Z");
  const fake = list(JSON.stringify([ghPull(7), old]));
  const r = await new GhClosedPulls(fake).closedSince(SINCE);
  expect(r).toEqual({
    ok: true,
    value: {
      truncated: false,
      pulls: [
        {
          number: 7,
          title: "fix: thing",
          body: "Generated by `shipwright pipeline`",
          headRef: "ci/issue-1",
          labels: ["shipwright:test-run"],
          createdAtMs: Date.UTC(2026, 10, 1),
          mergeSha: null,
          mergedAtMs: null,
          closedAtMs: Date.UTC(2026, 10, 2),
          commits: [],
        },
      ],
    },
  });
  // No --search (the index drops some closed PRs) and no commits (GraphQL node cap).
  expect(fake.calls[0]?.argv).toEqual([
    "gh",
    "pr",
    "list",
    "--state",
    "closed",
    "--limit",
    String(MAX_CLOSED_PULLS + 1),
    "--json",
    "number,title,body,headRefName,labels,createdAt,mergedAt,closedAt,mergeCommit",
  ]);
});

test("more PRs than the cap is reported as truncated", async () => {
  const many = Array.from({ length: MAX_CLOSED_PULLS + 1 }, (_, i) => ghPull(i));
  const r = await new GhClosedPulls(list(JSON.stringify(many))).closedSince(SINCE);
  expect(r.ok && r.value.truncated).toBe(true);
  expect(r.ok && r.value.pulls.length).toBe(MAX_CLOSED_PULLS);
});

test("reads one PR's commits with every author identity", async () => {
  const stdout = JSON.stringify({
    commits: [
      {
        committedDate: "2026-11-01T01:00:00Z",
        authors: [
          { login: "", name: "shipwright[bot]", email: "shipwright[bot]@users.noreply.github.com" },
          { login: "sethdford", name: null },
        ],
      },
    ],
  });
  const fake = runner(["gh", "pr", "view"], stdout);
  const r = await new GhClosedPulls(fake).commits(194);
  expect(r).toEqual({
    ok: true,
    value: [
      {
        identities: [
          "",
          "shipwright[bot]",
          "shipwright[bot]@users.noreply.github.com",
          "sethdford",
          "",
          "",
        ],
        atMs: Date.UTC(2026, 10, 1, 1),
      },
    ],
  });
  expect(fake.calls[0]?.argv).toEqual(["gh", "pr", "view", "194", "--json", "commits"]);
});

test("gh failures and unexpected output are errors", async () => {
  const auth = await new GhClosedPulls(list("", 1, "HTTP 401: Bad credentials")).closedSince(SINCE);
  expect(!auth.ok && auth.error.kind).toBe("auth");
  const bad = await new GhClosedPulls(list(JSON.stringify([{ number: "x" }]))).closedSince(SINCE);
  expect(bad.ok).toBe(false);
  const view = runner(["gh", "pr", "view"], JSON.stringify({ commits: "nope" }));
  expect((await new GhClosedPulls(view).commits(1)).ok).toBe(false);
});
