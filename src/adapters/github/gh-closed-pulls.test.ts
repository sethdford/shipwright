import { expect, test } from "bun:test";
import { FakeProcessRunner } from "../../testing/fake-process-runner";
import { GhClosedPulls, MAX_CLOSED_PULLS } from "./gh-closed-pulls";

const SINCE = Date.UTC(2026, 9, 27, 12);

const ghPull = (number: number) => ({
  number,
  title: "fix: thing",
  body: "Generated by `shipwright pipeline`",
  headRefName: "ci/issue-1",
  createdAt: "2026-11-01T00:00:00Z",
  mergedAt: "2026-11-02T00:00:00Z",
  closedAt: "2026-11-02T00:00:00Z",
  commits: [
    {
      committedDate: "2026-11-01T01:00:00Z",
      authors: [
        { login: "", name: "shipwright[bot]", email: "shipwright[bot]@users.noreply.github.com" },
      ],
    },
  ],
});

function runner(stdout: string, exitCode = 0, stderr = "") {
  return new FakeProcessRunner([
    { prefix: ["gh", "pr", "list"], result: { exitCode, stdout, stderr } },
  ]);
}

test("maps closed PRs to records and queries the window by close date", async () => {
  const fake = runner(JSON.stringify([{ ...ghPull(7), mergedAt: null }]));
  const r = await new GhClosedPulls(fake).closedSince(SINCE);
  expect(r).toEqual({
    ok: true,
    value: {
      truncated: false,
      pulls: [
        {
          number: 7,
          title: "fix: thing",
          body: "Generated by `shipwright pipeline`",
          headRef: "ci/issue-1",
          createdAtMs: Date.UTC(2026, 10, 1),
          mergedAtMs: null,
          closedAtMs: Date.UTC(2026, 10, 2),
          commits: [
            {
              identities: ["", "shipwright[bot]", "shipwright[bot]@users.noreply.github.com"],
              atMs: Date.UTC(2026, 10, 1, 1),
            },
          ],
        },
      ],
    },
  });
  expect(fake.calls[0]?.argv).toEqual([
    "gh",
    "pr",
    "list",
    "--state",
    "closed",
    "--search",
    "closed:>=2026-10-27",
    "--limit",
    "301",
    "--json",
    "number,title,body,headRefName,createdAt,mergedAt,closedAt,commits",
  ]);
});

test("more PRs than the cap is reported as truncated", async () => {
  const many = Array.from({ length: MAX_CLOSED_PULLS + 1 }, (_, i) => ghPull(i));
  const r = await new GhClosedPulls(runner(JSON.stringify(many))).closedSince(SINCE);
  expect(r.ok && r.value.truncated).toBe(true);
  expect(r.ok && r.value.pulls.length).toBe(MAX_CLOSED_PULLS);
});

test("gh failures and unexpected output are errors", async () => {
  const auth = await new GhClosedPulls(runner("", 1, "HTTP 401: Bad credentials")).closedSince(
    SINCE,
  );
  expect(!auth.ok && auth.error.kind).toBe("auth");
  const bad = await new GhClosedPulls(runner(JSON.stringify([{ number: "x" }]))).closedSince(SINCE);
  expect(bad.ok).toBe(false);
});
