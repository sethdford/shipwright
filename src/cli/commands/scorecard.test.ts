import { describe, expect, test } from "bun:test";
import type { PullRecord, QualityPorts } from "../../contexts/quality";
import { err, ok } from "../../shared/kernel/result";
import { captureIO, commandContext } from "../../testing/cli-harness";
import { scorecardCommand } from "./scorecard";

const NOW = Date.UTC(2026, 10, 26);
const DAY = 86_400_000;

const pull = (number: number, over: Partial<PullRecord> = {}): PullRecord => ({
  number,
  title: "fix",
  body: "Generated by `shipwright pipeline`",
  headRef: `fix/${number}`,
  createdAtMs: NOW - 3 * DAY,
  mergedAtMs: NOW - 2 * DAY,
  closedAtMs: NOW - 2 * DAY,
  commits: [],
  ...over,
});

function quality(truncated = false): QualityPorts {
  return {
    now: () => NOW,
    pulls: {
      closedSince: async () => ok({ pulls: [pull(1), pull(2, { mergedAtMs: null })], truncated }),
    },
    spend: { between: async () => ok(null) },
  };
}

async function run(args: string[], ports: QualityPorts = quality()) {
  const io = captureIO();
  const code = await scorecardCommand.run(
    args,
    commandContext(io, undefined, {}, undefined, ports),
  );
  return { code, io };
}

describe("scorecard", () => {
  test("text output shows the window and the merge rate", async () => {
    const { code, io } = await run([]);
    expect(code).toBe(0);
    const text = io.outLines.join("\n");
    expect(text).toContain("2026-10-27 → 2026-11-26 (30 days)");
    expect(text).toMatch(/Merge rate\s+50\.0%/);
    expect(text).toMatch(/Cost per merged PR\s+unknown/);
  });

  test("markdown output is a table for the public page", async () => {
    const { io } = await run(["--format", "markdown", "--days", "7"]);
    const md = io.outLines.join("\n");
    expect(md).toStartWith("## Shipwright delivery scorecard");
    expect(md).toContain("| Merge rate | 50.0% | merged ÷ closed |");
    expect(md).toContain("(7 days)");
  });

  test("json output is the report", async () => {
    const { io } = await run(["--format", "json"]);
    expect(JSON.parse(io.outLines.join("\n"))).toMatchObject({
      truncated: false,
      card: { merged: 1 },
    });
  });

  test("a truncated source warns on stderr", async () => {
    const { io } = await run(["--format", "markdown"], quality(true));
    expect(io.errLines[0]).toContain("partial");
    expect(io.outLines.join("\n")).toContain("**Partial:**");
  });

  test("an unreadable source exits 1", async () => {
    const ports = {
      ...quality(),
      pulls: { closedSince: async () => err({ kind: "auth" as const, message: "401" }) },
    };
    expect((await run([], ports)).code).toBe(1);
  });

  test("bad arguments exit 2 and help exits 0", async () => {
    expect((await run(["--help"])).code).toBe(0);
    expect((await run(["--days", "0"])).code).toBe(2);
    expect((await run(["--days", "400"])).code).toBe(2);
    expect((await run(["--format", "html"])).code).toBe(2);
    expect((await run(["--days"])).code).toBe(2);
    expect((await run(["--nope", "1"])).code).toBe(2);
  });
});
