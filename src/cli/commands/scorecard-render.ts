import type { Scorecard, ScorecardReport } from "../../contexts/quality";

const pct = (v: number | null): string => (v === null ? "—" : `${(v * 100).toFixed(1)}%`);
const usd = (v: number | null): string => (v === null ? "unknown" : `$${v.toFixed(2)}`);
const hrs = (v: number | null): string => (v === null ? "—" : `${v.toFixed(1)} h`);
const day = (ms: number): string => new Date(ms).toISOString().slice(0, 10);

/** Metric rows shared by the text and markdown renderers: [label, value, detail]. */
export function scorecardRows(c: Scorecard): [string, string, string][] {
  return [
    [
      "Agent PRs closed",
      String(c.closed),
      `${c.merged} merged, ${c.abandoned} closed unmerged; ${c.excluded} test run(s) left out`,
    ],
    ["Merge rate", pct(c.mergeRate), "merged ÷ closed"],
    [
      "Merged without human help",
      pct(c.cleanMergeRate),
      `${c.mergedClean} of ${c.merged}: every commit by the factory, not reverted`,
    ],
    [
      "Revert rate",
      pct(c.revertRate),
      `${c.reverted} reverted within 14 days; ${c.revertWindowOpen} still inside the window`,
    ],
    ["With human commits", String(c.reworked), "merged PRs with any commit not by the factory"],
    ["Median time to merge", hrs(c.medianHoursToMerge), "PR opened → merged"],
    ["Model spend", usd(c.spendUsd), "local cost ledger; unknown when it holds no real cost"],
    ["Cost per merged PR", usd(c.costPerMergeUsd), "spend ÷ merged"],
  ];
}

export function renderText(r: ScorecardReport): string {
  const c = r.card;
  const head = `Shipwright scorecard: ${day(c.fromMs)} → ${day(c.toMs)} (${c.windowDays} days)`;
  const rows = scorecardRows(c);
  const width = Math.max(...rows.map(([label]) => label.length));
  const lines = rows.map(([l, v, d]) => `  ${l.padEnd(width)}  ${v.padStart(9)}  ${d}`);
  const warn = r.truncated ? ["", "⚠ more PRs than one page: numbers are partial"] : [];
  return [head, "", ...lines, ...warn].join("\n");
}

const AGENT_NOTE =
  'Agent PRs are PRs whose body carries the pipeline\'s "Generated by `shipwright pipeline`" line ' +
  "or whose branch starts with `ci/issue-`. Test runs (label `shipwright:test-run`, a `test/` " +
  "branch, or listed with `--exclude`) are left out.";

/** Markdown for the public scorecard page: a table plus how each number is measured. */
export function renderMarkdown(r: ScorecardReport): string {
  const c = r.card;
  const rows = scorecardRows(c).map(([l, v, d]) => `| ${l} | ${v} | ${d} |`);
  const window = `Window: ${day(c.fromMs)} to ${day(c.toMs)} (${c.windowDays} days).`;
  const partial = "> **Partial:** the window holds more PRs than one page; older ones are missing.";
  return [
    "## Shipwright delivery scorecard",
    "",
    `${window} Generated by \`shipwright scorecard\`.`,
    "",
    "| Metric | Value | How it is measured |",
    "|---|---|---|",
    ...rows,
    "",
    AGENT_NOTE,
    ...(r.truncated ? ["", partial] : []),
  ].join("\n");
}
