import { buildScorecard } from "../../contexts/quality";
import type { Command } from "../command";
import { adapterFailure, isHelpRequest, usageError } from "../shared";
import { renderMarkdown, renderText } from "./scorecard-render";

const usage = `USAGE
  shipwright scorecard [--days N] [--exclude N[,N...]] [--format text|json|markdown]

DESCRIPTION
  Delivery scorecard for the factory's own PRs in this repository (Wave 2 plan W2-18): merge rate,
  merged without human help, revert rate (within 14 days), median time to merge, and cost per
  merged PR. Read-only: it lists closed PRs through gh, reads commits only for merged agent PRs,
  and reads spend from ~/.shipwright/costs.json. Spend is "unknown" when the ledger is missing or
  holds no real cost in the window (as on a CI runner).
  An agent PR carries "Generated by \`shipwright pipeline\`" in its body or a ci/issue- branch.
  A merged agent PR needed human help when any of its commits, before or after it opened, is by
  an author other than shipwright[bot], github-actions[bot] or claude[bot].
  Test runs of the pipeline are left out of every metric and counted as excluded: PRs labelled
  shipwright:test-run, PRs on a test/ branch, and the PR numbers given with --exclude.

OPTIONS
  --days N     Window in days, 1 to 365 (default 30)
  --exclude L  Comma-separated PR numbers to leave out as test runs (e.g. 195,6765)
  --format F   text (default), json, or markdown (for the public scorecard page)

EXIT CODES
  0  printed      1  could not read GitHub or the cost ledger      2  usage error`;

type Format = "text" | "json" | "markdown";
type Flags = { days: number; format: Format; exclude: number[] };

function parseExclude(value: string): number[] | null {
  if (!/^[1-9][0-9]{0,6}(,[1-9][0-9]{0,6})*$/.test(value)) return null;
  return value.split(",").map(Number);
}

function parseFlags(args: readonly string[]): Flags | string {
  let days = 30;
  let format: Format = "text";
  let exclude: number[] = [];
  for (let i = 0; i < args.length; i += 2) {
    const [flag, value] = [args[i], args[i + 1]];
    if (value === undefined) return `${flag} needs a value`;
    if (flag === "--days") {
      if (!/^[1-9][0-9]{0,2}$/.test(value) || Number(value) > 365) return "--days must be 1 to 365";
      days = Number(value);
    } else if (flag === "--format") {
      if (value !== "text" && value !== "json" && value !== "markdown") {
        return "--format must be text, json or markdown";
      }
      format = value;
    } else if (flag === "--exclude") {
      const list = parseExclude(value);
      if (list === null) return "--exclude must be PR numbers separated by commas";
      exclude = [...exclude, ...list];
    } else {
      return `unknown option: ${flag}`;
    }
  }
  return { days, format, exclude };
}

export const scorecardCommand: Command = {
  name: "scorecard",
  aliases: [],
  summary: "Delivery scorecard: merge, rework and revert rates and cost per merged PR",
  usage,
  async run(args, ctx) {
    const { io } = ctx;
    if (isHelpRequest(args)) {
      io.out(usage);
      return 0;
    }
    const flags = parseFlags(args);
    if (typeof flags === "string") return usageError(io, usage, flags);
    const r = await buildScorecard(ctx.quality(), {
      windowDays: flags.days,
      excludeNumbers: flags.exclude,
    });
    if (!r.ok) return adapterFailure(io, "scorecard", r.error);
    if (r.value.truncated) io.err("⚠ scorecard: more PRs than one page; numbers are partial");
    if (flags.format === "json") io.out(JSON.stringify(r.value, null, 2));
    else io.out(flags.format === "markdown" ? renderMarkdown(r.value) : renderText(r.value));
    return 0;
  },
};
