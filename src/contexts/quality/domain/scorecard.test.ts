import { expect, test } from "bun:test";
import {
  computeScorecard,
  DEFAULT_SCORECARD,
  isAgentPull,
  type PullRecord,
  pullsNeedingCommits,
  revertsByTarget,
  type ScorecardConfig,
} from "./scorecard";

const DAY = 86_400_000;
const NOW = Date.UTC(2026, 10, 26);
const config: ScorecardConfig = { ...DEFAULT_SCORECARD, nowMs: NOW };
const MARK = "Generated by `shipwright pipeline`";

function pull(n: number, over: Partial<PullRecord> = {}): PullRecord {
  return {
    number: n,
    title: `fix ${n}`,
    body: `Closes #${n + 1000}\n\n${MARK}`,
    headRef: `fix/thing-${n}`,
    createdAtMs: NOW - 20 * DAY,
    mergedAtMs: NOW - 19 * DAY,
    closedAtMs: NOW - 19 * DAY,
    commits: [{ identities: ["", "shipwright[bot]", ""], atMs: NOW - 20 * DAY - 1 }],
    ...over,
  };
}

const revert = (n: number, target: number, mergedAtMs: number): PullRecord =>
  pull(n, {
    title: `Revert "fix ${target}"`,
    body: `Reverts sethdford/shipwright#${target}`,
    headRef: `revert-${target}`,
    mergedAtMs,
    closedAtMs: mergedAtMs,
  });

test("a PR is the factory's by its body marker or its branch prefix", () => {
  expect(isAgentPull(pull(1), config)).toBe(true);
  expect(isAgentPull(pull(2, { body: "", headRef: "ci/issue-7" }), config)).toBe(true);
  expect(isAgentPull(pull(3, { body: "human work" }), config)).toBe(false);
});

test("reverts are keyed by the PR they revert, earliest merge wins", () => {
  const map = revertsByTarget([
    revert(10, 1, NOW - 5 * DAY),
    revert(11, 1, NOW - 9 * DAY),
    pull(12, { title: 'Revert "x"', body: "Reverts #2", mergedAtMs: null }),
  ]);
  expect([...map]).toEqual([[1, NOW - 9 * DAY]]);
});

test("counts merged, abandoned, reverted and reworked agent PRs in the window", () => {
  const human = { identities: ["sethdford", "Seth", "s@example.com"], atMs: NOW - 19.5 * DAY };
  const pulls = [
    pull(1),
    pull(2, { mergedAtMs: null }),
    pull(3, { commits: [human] }),
    pull(4),
    revert(5, 4, NOW - 10 * DAY),
    pull(6, { body: "a human PR" }),
    pull(7, { closedAtMs: NOW - 40 * DAY, mergedAtMs: NOW - 40 * DAY }),
  ];
  const card = computeScorecard(pulls, config, 12);
  expect(card).toMatchObject({
    closed: 4,
    merged: 3,
    abandoned: 1,
    mergeRate: 0.75,
    reworked: 1,
    reverted: 1,
    revertRate: 1 / 3,
    mergedClean: 1,
    cleanMergeRate: 1 / 3,
    medianHoursToMerge: 24,
    spendUsd: 12,
    costPerMergeUsd: 4,
    revertWindowOpen: 0,
  });
});

test("a human commit made before the PR opened is human work too", () => {
  const early = { identities: ["sethdford", "Seth", ""], atMs: NOW - 25 * DAY };
  const card = computeScorecard([pull(1, { commits: [early] })], config, null);
  expect(card).toMatchObject({ merged: 1, reworked: 1, mergedClean: 0 });
});

test("only merged agent PRs in the window need their commits read", () => {
  const pulls = [
    pull(1),
    pull(2, { mergedAtMs: null }),
    pull(3, { body: "human" }),
    pull(4, { closedAtMs: NOW - 40 * DAY }),
  ];
  expect(pullsNeedingCommits(pulls, config)).toEqual([1]);
});

test("a revert after the revert window does not count, and fresh merges are flagged", () => {
  const pulls = [
    pull(1, { mergedAtMs: NOW - 29 * DAY, closedAtMs: NOW - 29 * DAY }),
    revert(2, 1, NOW - 1 * DAY),
    pull(3, { mergedAtMs: NOW - 2 * DAY, closedAtMs: NOW - 2 * DAY }),
  ];
  const card = computeScorecard(pulls, config, null);
  expect(card).toMatchObject({
    merged: 2,
    reverted: 0,
    revertWindowOpen: 1,
    costPerMergeUsd: null,
  });
});

test("no agent PRs gives null rates, never zero", () => {
  const card = computeScorecard([], config, null);
  expect(card).toMatchObject({
    closed: 0,
    mergeRate: null,
    revertRate: null,
    medianHoursToMerge: null,
  });
});
