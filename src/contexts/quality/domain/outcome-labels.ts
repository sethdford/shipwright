import { type PullRecord, revertsByTarget } from "./scorecard";

/**
 * Which closed PRs the verifier learns from, and their labels. Pure.
 *
 * Label 1: merged and not reverted within the revert window ("merged and stayed merged").
 * Label 0: closed without merging, or merged and then reverted within the window.
 * Left out: dependency bots (closed in bulk when superseded, which says nothing about quality),
 * pipeline test runs, and PRs still open.
 */
export interface LabelConfig {
  readonly revertWindowDays: number;
  /** Body text that marks the factory's own PRs. */
  readonly agentMarkers: readonly string[];
  readonly agentBranchPrefixes: readonly string[];
  /** Extra PR numbers the operator knows the factory opened (older PRs carry no marker). */
  readonly agentNumbers: readonly number[];
  /** PR numbers to leave out (test runs, demos). */
  readonly excludeNumbers: readonly number[];
  readonly excludeLabels: readonly string[];
  readonly excludeBranchPrefixes: readonly string[];
  /** Sample weight of human PRs; 0 trains on the factory's PRs only. */
  readonly humanWeight: number;
}

export const DEFAULT_LABELS: LabelConfig = {
  revertWindowDays: 14,
  agentMarkers: ["Generated by `shipwright pipeline`", "via `shipwright pipeline`"],
  agentBranchPrefixes: ["ci/issue-", "pipeline/"],
  agentNumbers: [],
  excludeNumbers: [],
  excludeLabels: ["shipwright:test-run"],
  excludeBranchPrefixes: ["test/", "dependabot/", "renovate/"],
  humanWeight: 0.5,
};

export interface LabelledPull {
  readonly pull: PullRecord;
  readonly y: 0 | 1;
  readonly agent: boolean;
  readonly weight: number;
}

const DAY_MS = 86_400_000;

export function isFactoryPull(p: PullRecord, c: LabelConfig): boolean {
  return (
    c.agentNumbers.includes(p.number) ||
    c.agentMarkers.some((m) => p.body.includes(m)) ||
    c.agentBranchPrefixes.some((b) => p.headRef.startsWith(b))
  );
}

function excluded(p: PullRecord, c: LabelConfig): boolean {
  return (
    p.closedAtMs === null ||
    /^Revert "/.test(p.title) ||
    c.excludeNumbers.includes(p.number) ||
    p.labels.some((l) => c.excludeLabels.includes(l)) ||
    c.excludeBranchPrefixes.some((b) => p.headRef.startsWith(b))
  );
}

/** Labels every usable closed PR. Human PRs get `humanWeight`; with 0 they are dropped. */
export function labelPulls(pulls: readonly PullRecord[], c: LabelConfig): LabelledPull[] {
  const reverts = revertsByTarget(pulls);
  const out: LabelledPull[] = [];
  for (const pull of pulls) {
    if (excluded(pull, c)) continue;
    const agent = isFactoryPull(pull, c);
    const weight = agent ? 1 : c.humanWeight;
    if (weight <= 0) continue;
    const revertAt = reverts.get(pull.number);
    const reverted =
      pull.mergedAtMs !== null &&
      revertAt !== undefined &&
      revertAt - pull.mergedAtMs <= c.revertWindowDays * DAY_MS;
    const y: 0 | 1 = pull.mergedAtMs !== null && !reverted ? 1 : 0;
    out.push({ pull, y, agent, weight });
  }
  return out;
}
