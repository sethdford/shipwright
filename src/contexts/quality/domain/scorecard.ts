import { median } from "./ratchet";

const DAY_MS = 86_400_000;

/** A commit on a pull request: who wrote it (login, name and email, any may be empty) and when. */
export interface PullCommit {
  readonly identities: readonly string[];
  readonly atMs: number;
}

/** A closed pull request as the scorecard needs it (W2-18 measures from GitHub state). */
export interface PullRecord {
  readonly number: number;
  readonly title: string;
  readonly body: string;
  readonly headRef: string;
  readonly createdAtMs: number;
  readonly mergedAtMs: number | null;
  readonly closedAtMs: number | null;
  readonly commits: readonly PullCommit[];
}

export interface ScorecardConfig {
  readonly nowMs: number;
  readonly windowDays: number;
  /** A merge reverted within this many days counts as reverted (W2-18: 14). */
  readonly revertWindowDays: number;
  /** Text in a PR body that marks it as written by Shipwright. */
  readonly agentMarkers: readonly string[];
  /** Head-branch prefixes that mark a PR as written by Shipwright. */
  readonly agentBranchPrefixes: readonly string[];
  /** Commit authors that are the factory itself; any other author after the PR opened is rework. */
  readonly agentAuthors: readonly string[];
}

export const DEFAULT_SCORECARD: Omit<ScorecardConfig, "nowMs"> = {
  windowDays: 30,
  revertWindowDays: 14,
  agentMarkers: ["Generated by `shipwright pipeline`"],
  agentBranchPrefixes: ["ci/issue-"],
  agentAuthors: ["shipwright[bot]", "github-actions[bot]", "claude[bot]"],
};

export interface Scorecard {
  readonly fromMs: number;
  readonly toMs: number;
  readonly windowDays: number;
  /** Agent PRs closed (merged or not) in the window. */
  readonly closed: number;
  readonly merged: number;
  readonly abandoned: number;
  readonly mergeRate: number | null;
  /** Merged with no human commit after it opened and not reverted: "merged without rework". */
  readonly mergedClean: number;
  readonly cleanMergeRate: number | null;
  readonly reworked: number;
  readonly reverted: number;
  readonly revertRate: number | null;
  /** Merged too recently for the revert window to have closed; their revert status may change. */
  readonly revertWindowOpen: number;
  readonly medianHoursToMerge: number | null;
  readonly spendUsd: number | null;
  readonly costPerMergeUsd: number | null;
}

export function isAgentPull(pull: PullRecord, config: ScorecardConfig): boolean {
  return (
    config.agentMarkers.some((m) => pull.body.includes(m)) ||
    config.agentBranchPrefixes.some((p) => pull.headRef.startsWith(p))
  );
}

/** Merge times of reverts, keyed by the PR number they revert (GitHub's "Reverts owner/repo#N"). */
export function revertsByTarget(pulls: readonly PullRecord[]): Map<number, number> {
  const out = new Map<number, number>();
  for (const p of pulls) {
    if (p.mergedAtMs === null || !/^Revert "/.test(p.title)) continue;
    for (const m of p.body.matchAll(/(?:^|[\s(])(?:[\w.-]+\/[\w.-]+)?#(\d+)\b/g)) {
      const target = Number(m[1]);
      const prev = out.get(target);
      if (target !== p.number && (prev === undefined || p.mergedAtMs < prev))
        out.set(target, p.mergedAtMs);
    }
  }
  return out;
}

function humanCommitAfterOpen(pull: PullRecord, agentAuthors: readonly string[]): boolean {
  const agents = new Set(agentAuthors.map((a) => a.toLowerCase()));
  return pull.commits.some(
    (c) =>
      c.atMs > pull.createdAtMs &&
      !c.identities.some((id) => id !== "" && agents.has(id.toLowerCase())),
  );
}

const rate = (n: number, d: number): number | null => (d > 0 ? n / d : null);

function closedInWindow(pulls: readonly PullRecord[], config: ScorecardConfig, fromMs: number) {
  return pulls.filter(
    (p) =>
      isAgentPull(p, config) &&
      p.closedAtMs !== null &&
      p.closedAtMs >= fromMs &&
      p.closedAtMs <= config.nowMs,
  );
}

/** Merged PRs split into reverted (within the window), reworked, and clean. */
function outcomes(
  merged: readonly PullRecord[],
  all: readonly PullRecord[],
  config: ScorecardConfig,
) {
  const reverts = revertsByTarget(all);
  const revertMs = config.revertWindowDays * DAY_MS;
  const reverted = new Set(
    merged.filter((p) => {
      const at = reverts.get(p.number);
      return at !== undefined && p.mergedAtMs !== null && at - p.mergedAtMs <= revertMs;
    }),
  );
  const reworked = new Set(merged.filter((p) => humanCommitAfterOpen(p, config.agentAuthors)));
  const clean = merged.filter((p) => !reverted.has(p) && !reworked.has(p)).length;
  const windowOpen = merged.filter((p) => (p.mergedAtMs ?? 0) > config.nowMs - revertMs).length;
  return { reverted: reverted.size, reworked: reworked.size, clean, windowOpen };
}

/** W2-18 delivery scorecard over agent PRs closed in the window. Pure. */
export function computeScorecard(
  pulls: readonly PullRecord[],
  config: ScorecardConfig,
  spendUsd: number | null,
): Scorecard {
  const fromMs = config.nowMs - config.windowDays * DAY_MS;
  const closed = closedInWindow(pulls, config, fromMs);
  const merged = closed.filter((p) => p.mergedAtMs !== null);
  const o = outcomes(merged, pulls, config);
  const hours = merged.map((p) => ((p.mergedAtMs ?? 0) - p.createdAtMs) / 3_600_000);
  return {
    fromMs,
    toMs: config.nowMs,
    windowDays: config.windowDays,
    closed: closed.length,
    merged: merged.length,
    abandoned: closed.length - merged.length,
    mergeRate: rate(merged.length, closed.length),
    mergedClean: o.clean,
    cleanMergeRate: rate(o.clean, merged.length),
    reworked: o.reworked,
    reverted: o.reverted,
    revertRate: rate(o.reverted, merged.length),
    revertWindowOpen: o.windowOpen,
    medianHoursToMerge: median(hours),
    spendUsd,
    costPerMergeUsd: spendUsd === null || merged.length === 0 ? null : spendUsd / merged.length,
  };
}
