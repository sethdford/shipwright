import { CORS_HEADERS } from "../middleware/constants.js";
import { redeemJoinToken } from "../services/auth-flow.js";

/**
 * Join and invite routes. A token is never part of a URL: it travels in a request header
 * (`X-Shipwright-Join-Token`, `X-Shipwright-Invite-Token`) and nothing here logs it. The old
 * path forms (`GET /api/join/<token>`, `GET /api/team/invite/<token>`) are retired and refused
 * with 410 without touching the token, so a leaked URL cannot be replayed through them.
 */

export const JOIN_TOKEN_HEADER = "X-Shipwright-Join-Token";
export const INVITE_TOKEN_HEADER = "X-Shipwright-Invite-Token";

export type JoinTokenRecord = Record<string, unknown> & { token: string; used?: boolean };

export interface JoinRouteDeps {
  loadJoinTokens(): JoinTokenRecord[];
  /** Persists the list after a redemption (the server writes the file atomically). */
  saveJoinTokens(tokens: JoinTokenRecord[]): void;
  /** Returns the live invite entry, or undefined when unknown or expired (the server prunes). */
  lookupInvite(token: string): { expires_at: string } | undefined;
  /** Dashboard origin the verify response reports back to the worker. */
  dashboardUrl: string;
}

const JSON_HEADERS = { "Content-Type": "application/json", ...CORS_HEADERS };
const SENSITIVE_RESPONSE = { "Referrer-Policy": "no-referrer", "Cache-Control": "no-store" };

const RETIRED_MESSAGE =
  "join and invite tokens are no longer accepted in URLs; upgrade shipwright and use the new join command";

/** The token header value, or "" when absent. Query strings and the path are never read. */
export function tokenFromHeader(req: Request, name: string): string {
  return (req.headers.get(name) || "").trim();
}

/** The worker bootstrap script. It carries no token: the token is spent when the script is served. */
export function generateJoinScript(dashboardUrl: string, maxWorkers: number): string {
  return `#!/usr/bin/env bash
set -euo pipefail
# Shipwright remote worker join script
# Generated by Shipwright Dashboard

DASHBOARD_URL="${dashboardUrl}"
MAX_WORKERS="${maxWorkers}"

echo "==> Joining Shipwright cluster..."
echo "    Dashboard: \${DASHBOARD_URL}"
echo "    Max workers: \${MAX_WORKERS}"

# Verify shipwright is installed
if ! command -v shipwright &>/dev/null && ! command -v sw &>/dev/null; then
  echo "ERROR: shipwright not found in PATH"
  echo "Install: curl -fsSL https://raw.githubusercontent.com/sethdford/shipwright/main/install.sh | bash"
  exit 1
fi

SW=\$(command -v shipwright || command -v sw)

# Register this machine with the dashboard
HOSTNAME=\$(hostname)
\$SW remote add "\${HOSTNAME}" \\
  --host "\$(hostname -f 2>/dev/null || hostname)" \\
  --max-workers "\${MAX_WORKERS}" 2>/dev/null || true

echo "==> Machine registered. Starting daemon..."
\$SW daemon start --max-parallel "\${MAX_WORKERS}"
`;
}

/** The command an operator runs on a worker: it prompts for the token and sends it on stdin. */
export function joinCommand(dashboardUrl: string): string {
  return [
    "printf 'Join token: '; read -rs SW_JOIN_TOKEN; echo;",
    `curl -fsSL -X POST -H 'Content-Type: application/json' -d '{}' -H @- '${dashboardUrl}/api/join'`,
    "< <(printf 'X-Shipwright-Join-Token: %s\\n' \"$SW_JOIN_TOKEN\") | bash; unset SW_JOIN_TOKEN",
  ].join(" ");
}

/** The command a team member runs; the token is prompted for, not passed as an argument. */
export function teamJoinCommand(dashboardUrl: string): string {
  return `shipwright connect join --url ${dashboardUrl}`;
}

/**
 * Handles the join and invite routes. Returns null for any other request, so the caller keeps
 * routing it.
 */
export function handleJoinRoutes(
  req: Request,
  pathname: string,
  deps: JoinRouteDeps,
): Response | null {
  if (pathname === "/api/join" && req.method === "POST") {
    return redeemJoinScript(req, deps);
  }
  if (pathname.startsWith("/api/join/")) {
    return retired("text/plain");
  }
  if (pathname === "/api/team/invite/verify" && req.method === "POST") {
    return verifyInvite(req, deps);
  }
  if (pathname.startsWith("/api/team/invite/")) {
    return retired("application/json");
  }
  return null;
}

function redeemJoinScript(req: Request, deps: JoinRouteDeps): Response {
  const token = tokenFromHeader(req, JOIN_TOKEN_HEADER);
  if (!token) {
    return new Response(
      JSON.stringify({ error: `missing ${JOIN_TOKEN_HEADER} header` }),
      { status: 401, headers: { ...JSON_HEADERS, ...SENSITIVE_RESPONSE } },
    );
  }
  try {
    const tokens = deps.loadJoinTokens();
    // Single use: an unknown or already-redeemed token gets the same refusal (no replay).
    const redeemed = redeemJoinToken(tokens, token, new Date().toISOString());
    if (!redeemed.ok) {
      return new Response(
        "#!/usr/bin/env bash\necho 'ERROR: Invalid, expired or already-used join token'\nexit 1\n",
        { status: 410, headers: { "Content-Type": "text/plain", ...SENSITIVE_RESPONSE, ...CORS_HEADERS } },
      );
    }
    const maxWorkers = (redeemed.entry.max_workers as number) || 4;
    deps.saveJoinTokens(tokens);
    return new Response(generateJoinScript(deps.dashboardUrl, maxWorkers), {
      headers: { "Content-Type": "text/plain", ...SENSITIVE_RESPONSE, ...CORS_HEADERS },
    });
  } catch {
    // Fixed text: never splice error data into a script the client pipes to bash.
    return new Response(
      "#!/usr/bin/env bash\necho 'ERROR: dashboard could not issue the join script'\nexit 1\n",
      { status: 500, headers: { "Content-Type": "text/plain", ...SENSITIVE_RESPONSE, ...CORS_HEADERS } },
    );
  }
}

function verifyInvite(req: Request, deps: JoinRouteDeps): Response {
  const token = tokenFromHeader(req, INVITE_TOKEN_HEADER);
  if (!token) {
    return new Response(JSON.stringify({ valid: false, error: `missing ${INVITE_TOKEN_HEADER} header` }), {
      status: 400,
      headers: { ...JSON_HEADERS, ...SENSITIVE_RESPONSE },
    });
  }
  const entry = deps.lookupInvite(token);
  if (!entry) {
    return new Response(JSON.stringify({ valid: false, error: "Invalid or expired token" }), {
      status: 404,
      headers: { ...JSON_HEADERS, ...SENSITIVE_RESPONSE },
    });
  }
  return new Response(
    JSON.stringify({
      valid: true,
      dashboard_url: deps.dashboardUrl,
      team_name: "shipwright",
      expires_at: entry.expires_at,
    }),
    { headers: { ...JSON_HEADERS, ...SENSITIVE_RESPONSE } },
  );
}

function retired(contentType: string): Response {
  const body =
    contentType === "text/plain"
      ? `#!/usr/bin/env bash\necho 'ERROR: ${RETIRED_MESSAGE}'\nexit 1\n`
      : JSON.stringify({ valid: false, error: RETIRED_MESSAGE });
  return new Response(body, {
    status: 410,
    headers: { "Content-Type": contentType, ...SENSITIVE_RESPONSE, ...CORS_HEADERS },
  });
}
