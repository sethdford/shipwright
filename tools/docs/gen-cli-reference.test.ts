import { expect, test } from "bun:test";
import { isStale, renderCliReference } from "./gen-cli-reference";

const hello = {
  name: "hello",
  aliases: ["hi"],
  summary: "Say hi",
  usage: "USAGE\n  shipwright hello",
  run: async () => 0,
};

test("renders a heading, a generated-file notice and each command's usage", () => {
  const md = renderCliReference([hello]);
  expect(md).toStartWith("# CLI reference\n\n<!-- Generated by tools/docs/gen-cli-reference.ts");
  expect(md).toContain(
    "## `hello`\n\nSay hi\n\nAliases: `hi`\n\n```text\nUSAGE\n  shipwright hello\n```",
  );
});

test("output is sorted by name and ends with exactly one trailing newline", () => {
  const md = renderCliReference([{ ...hello, name: "zed" }, hello]);
  expect(md.indexOf("## `hello`")).toBeLessThan(md.indexOf("## `zed`"));
  expect(md.endsWith("```\n")).toBe(true);
  expect(md.endsWith("\n\n")).toBe(false);
});

test("isStale detects drift and accepts identical content", () => {
  const md = renderCliReference([hello]);
  expect(isStale(md, md)).toBe(false);
  expect(isStale("", md)).toBe(true);
  expect(isStale(`${md}\n`, md)).toBe(true);
  expect(isStale(md.replace("Say hi", "Say hello"), md)).toBe(true);
});
