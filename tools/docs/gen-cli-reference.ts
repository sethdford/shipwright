import { join, resolve } from "node:path";
import type { Command } from "../../src/cli/command";
import { commands } from "../../src/cli/commands";

const ROOT = resolve(import.meta.dir, "../..");
const TARGET = join(ROOT, "docs/reference/cli.md");
const TARGET_REL = "docs/reference/cli.md";

function renderCommand(c: Command): string {
  const aliases = c.aliases.length
    ? `Aliases: ${c.aliases.map((a) => `\`${a}\``).join(", ")}\n\n`
    : "";
  return `## \`${c.name}\`\n\n${c.summary}\n\n${aliases}\`\`\`text\n${c.usage}\n\`\`\`\n`;
}

export function renderCliReference(cmds: readonly Command[]): string {
  const sections = [...cmds].sort((a, b) => a.name.localeCompare(b.name)).map(renderCommand);
  return [
    "# CLI reference",
    "",
    "<!-- Generated by tools/docs/gen-cli-reference.ts from src/cli/commands. Do not edit. -->",
    "",
    "Commands implemented in TypeScript. Commands still in bash are listed in docs/plans/port/progress.json.",
    "",
    ...sections,
  ].join("\n");
}

export function isStale(current: string, rendered: string): boolean {
  return current !== rendered;
}

if (import.meta.main) {
  const md = renderCliReference(commands);
  if (Bun.argv.includes("--check")) {
    const file = Bun.file(TARGET);
    const current = (await file.exists()) ? await file.text() : "";
    if (isStale(current, md)) {
      console.error(`${TARGET_REL} is stale. Run: bun run docs:gen`);
      process.exit(1);
    }
  } else {
    await Bun.write(TARGET, md);
  }
}
